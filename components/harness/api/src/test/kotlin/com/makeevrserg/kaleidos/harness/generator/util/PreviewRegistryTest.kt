@file:Suppress("FunctionNaming")

package com.makeevrserg.kaleidos.harness.generator.util

import com.makeevrserg.kaleidos.harness.model.HarnessFixtures.preview
import com.makeevrserg.kaleidos.harness.model.HarnessFixtures.privatePreview
import com.makeevrserg.kaleidos.harness.model.PreviewModulePlan
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

class PreviewRegistryTest {

    private val module = PreviewModulePlan(
        gradlePath = ":components:ui",
        directory = "/project/components/ui",
        previews = listOf(preview("com.example.CardPreview"), preview("com.example.ButtonPreview")),
        privatePreviewFiles = emptyList()
    )

    @Test
    fun GIVEN_module_previews_WHEN_create_THEN_the_file_lands_in_the_package_of_the_module() {
        val file = module.generatePreviewRegistry()

        assertEquals(
            "kotlin/kaleidos/generated/m_components_ui/PreviewRegistry.kt",
            file.relativePath
        )
        assertTrue(file.content.startsWith("// Generated by the Kaleidos plugin"), file.content)
        assertTrue(file.content.contains("package kaleidos.generated.m_components_ui"), file.content)
    }

    @Suppress("StringShouldBeRawString")
    @Test
    fun GIVEN_module_previews_WHEN_create_THEN_every_preview_is_listed_and_callable() {
        val content = module.generatePreviewRegistry().content

        assertTrue(content.contains("        \"com.example.CardPreview\","), content)
        assertTrue(content.contains("        \"com.example.ButtonPreview\"\n"), content)
        assertTrue(content.contains("            \"com.example.CardPreview\" -> com.example.CardPreview()"), content)
    }

    @Suppress("StringShouldBeRawString")
    @Test
    fun GIVEN_private_preview_WHEN_create_THEN_it_is_called_through_its_wrapper() {
        val content = module.copy(
            previews = listOf(privatePreview("com.example.CardPreview"))
        ).generatePreviewRegistry().content

        assertTrue(
            content.contains(
                "            \"com.example.CardPreview\" -> " +
                    "com.example.KaleidosPreview_com_example_CardPreview_CardPreview()"
            ),
            content
        )
    }
}
