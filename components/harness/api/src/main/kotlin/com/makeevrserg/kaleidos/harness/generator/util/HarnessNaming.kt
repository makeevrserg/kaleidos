package com.makeevrserg.kaleidos.harness.generator.util

import com.makeevrserg.kaleidos.harness.model.HarnessPreview
import com.makeevrserg.kaleidos.harness.util.KOTLIN_DIRECTORY

internal const val PAGE_PACKAGE = "kaleidos.generated"
internal const val REGISTRY_CLASS = "PreviewRegistry"
internal const val HEADER = "// Generated by the Kaleidos plugin. Do not edit, do not commit."
private const val MODULE_SEGMENT_PREFIX = "m"
private const val FQN_SEPARATOR = '.'
private const val KOTLIN_EXTENSION = ".kt"
private const val PRIVATE_PREVIEW_WRAPPER_PREFIX = "KaleidosPreview_"
private const val PRIVATE_PREVIEW_FILES_DIRECTORY = "kaleidos/sources"

private fun moduleSegment(gradlePath: String): String {
    val sanitized = gradlePath.map { character ->
        if (character.isLetterOrDigit()) character.lowercaseChar() else '_'
    }
    return MODULE_SEGMENT_PREFIX + sanitized.joinToString(separator = "")
}

private fun identifier(value: String): String {
    return value.map { character -> if (character.isLetterOrDigit()) character else '_' }
        .joinToString(separator = "")
}

internal fun HarnessPreview.functionName(): String = fqn.substringAfterLast(FQN_SEPARATOR)

internal fun HarnessPreview.privatePreviewWrapperName(): String {
    val file = identifier(sourcePath.removeSuffix(KOTLIN_EXTENSION))
    return "$PRIVATE_PREVIEW_WRAPPER_PREFIX${file}_${functionName()}"
}

internal fun HarnessPreview.callFqn(): String {
    if (!isPrivate) return fqn
    val packageName = fqn.substringBeforeLast(FQN_SEPARATOR, missingDelimiterValue = "")
    val wrapperName = privatePreviewWrapperName()
    if (packageName.isEmpty()) return wrapperName
    return "$packageName$FQN_SEPARATOR$wrapperName"
}

internal fun privatePreviewFileCopyPath(sourcePath: String): String {
    return "$KOTLIN_DIRECTORY/$PRIVATE_PREVIEW_FILES_DIRECTORY/$sourcePath"
}

internal fun registryPackage(gradlePath: String): String = "$PAGE_PACKAGE.${moduleSegment(gradlePath)}"

internal fun registryFqn(gradlePath: String): String = "${registryPackage(gradlePath)}.$REGISTRY_CLASS"

internal fun packageDirectory(packageName: String): String = packageName.replace('.', '/')
