private fun groovyString(value: String): String {
    val escaped = value.replace("\\", "\\\\").replace("'", "\\'")
    return "'$escaped'"
}

private fun groovyStringList(values: List<String>): String {
    return values.joinToString(
        prefix = "[",
        postfix = "]",
        transform = ::groovyString
    )
}

private fun injectionEntry(
    gradlePath: String,
    kotlinDirectory: String,
    resourcesDirectory: String?,
    devServerPort: Int?,
    excludedSourcePaths: List<String>
): List<String> {
    return buildList {
        add("    ${groovyString(gradlePath)}: [")
        add("        kotlinSrcDir: ${groovyString(kotlinDirectory)},")
        add("        resourcesSrcDir: ${resourcesDirectory?.let(::groovyString) ?: "null"},")
        add("        devServerPort: ${devServerPort ?: "null"},")
        add("        outputFileName: ${groovyString(WEBPACK_BUNDLE_NAME)},")
        add("        excludedSourcePaths: ${groovyStringList(excludedSourcePaths)}")
        add("    ],")
    }
}

private fun List<String>.withoutTrailingComma(): List<String> {
    val lastEntryIndex = indexOfLast { line -> line.endsWith(MAP_ENTRY_END) }
    if (lastEntryIndex < 0) return this
    return mapIndexed { index, line ->
        if (index == lastEntryIndex) line.removeSuffix(MAP_ENTRY_SEPARATOR) else line
    }
}

private fun PreviewModulePlan.privatePreviewSourcePaths(): List<String> {
    return privatePreviewFiles.map(PrivatePreviewFile::sourcePath)
}

private fun HarnessPlan.injections(): List<String> {
    val hostDirectory = host.directory
    val isWebpack = host.kind == DevServerKind.WEBPACK
    val registryOnlyModules = modules.filterNot { module -> module.directory == hostDirectory }
    val hostPrivatePreviewSourcePaths = modules
        .filter { module -> module.directory == hostDirectory }
        .flatMap(PreviewModulePlan::privatePreviewSourcePaths)
    return buildList {
        add("def previewInjections = [")
        registryOnlyModules.forEach { module ->
            addAll(
                injectionEntry(
                    gradlePath = module.gradlePath,
                    kotlinDirectory = harnessKotlinRoot(module.directory).toString(),
                    resourcesDirectory = null,
                    devServerPort = null,
                    excludedSourcePaths = module.privatePreviewSourcePaths()
                )
            )
        }
        addAll(
            injectionEntry(
                gradlePath = host.gradlePath,
                kotlinDirectory = harnessKotlinRoot(hostDirectory).toString(),
                resourcesDirectory = harnessResourcesRoot(hostDirectory).toString().takeIf { isWebpack },
                devServerPort = host.devServerPort,
                excludedSourcePaths = host.excludedSourcePaths + hostPrivatePreviewSourcePaths
            )
        )
        add("]")
    }.withoutTrailingComma()
}

internal fun HarnessPlan.generatePreviewInitScript(): GeneratedFile {
    val lines = buildList {
        add(GROOVY_HEADER)
        add("")
        addAll(injections())
        add("")
        addAll(SCRIPT_BODY)
    }
    return GeneratedFile(
        relativePath = INIT_SCRIPT_NAME,
        content = lines.joinToString(separator = "\n", postfix = "\n")
    )
}
